"""Writes src/DesktopBuddy.Core/CatBreedArt.cs: every pose of the ten designed cats and the nine dogs as pixel grids.
Run from this folder: python3 export_cs.py"""
import os
import posekit, final, drafts, dogkit, dogs

W, H = posekit.W, posekit.H
OUT = os.path.join(os.path.dirname(__file__), '..', '..', 'src', 'DesktopBuddy.Core', 'CatBreedArt.cs')
# Greek letters at the end for coats with a lot of shades (the curly poodle).
CHARS = ("abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789!#$%&()*+,-/:;<=>?@[]^_`{|}~"
         "αβγδεζηθικλμνξοπρστυφχψωΓΔΘΛΞΠΣΦΨΩ")
SWEAT = [(1, 0), (0, 1), (1, 1), (2, 1), (0, 2), (1, 2), (2, 2), (1, 3)]   # drop shape, as in CatPixels
# Poses that play one after another share one sweat spot, so the drop stays put while the body moves under it.
SWEAT_GROUPS = [['WalkA', 'WalkB'], ['Sit', 'SitBlink', 'SitTail'], ['LookUp'], ['RunA', 'RunB', 'RunC', 'RunD']]
SWEAT_POSES = [p for group in SWEAT_GROUPS for p in group]
NOSE_POSES = ['SitBlink', 'NapA', 'NapB', 'Drowsy', 'Curl']
BUBBLE = [(dx, dy) for dx in range(3) for dy in range(3)]
FRONT_HEADS = {'bean', 'puff', 'pebble', 'sprout'}

def buddies():
    """(enum name, poses, canvas for a pose, renderer of a canvas) for each designed cat and dog.
    Dogs have every cat pose plus their bone poses, and the bone is drawn over the dog."""
    for name, _, kw, coat in drafts.DRAFTS:
        yield (f'{name}Cartoon', posekit.POSES, lambda pose, kw=kw: posekit.pose_canvas(pose, **kw),
               lambda cv, name=name, coat=coat: drafts.render(name, drafts.fluffy(cv.g) if name == 'Puff' else cv.g, coat))
    for name, _, kind, fluff, coat in final.CATS:
        yield (f'{name}Realistic', posekit.POSES, lambda pose, kind=kind: posekit.pose_canvas(pose, kind),
               lambda cv, fluff=fluff, coat=coat: final.render(final.fluffy(cv.g) if fluff else cv.g, coat))
    for name, _, kind, head, tail, fluff, coat in dogs.DOGS:
        yield (name, dogkit.POSES, lambda pose, a=(kind, head, tail): dogkit.pose_canvas(pose, *a),
               lambda cv, fluff=fluff, coat=coat: dogs.draw_props(final.render(final.fluffy(cv.g) if fluff else cv.g, coat), cv.props))

def clear(img, x, y, shape, margin=1):
    for dx, dy in shape:
        for mx in range(-margin, margin + 1):
            for my in range(-margin, margin + 1):
                px, py = x + dx + mx, y + dy + my
                if not (0 <= px < W and 0 <= py < H):
                    if mx == 0 and my == 0: return False
                    continue
                if img.getpixel((px, py))[3]: return False
    return True

def sweat_spot(frames):
    """Top-left of a drop that is clear of the cat in every (img, headbox) of a group: as close behind the head as it fits."""
    r0 = min(head[0] for _, head in frames)
    c0 = min(head[1] for _, head in frames)
    fits = lambda x, y: all(clear(img, x, y, SWEAT) for img, _ in frames)
    top = max(0, r0 - 1)
    spots = [(x, y) for y in range(r0 + 5) for x in range(c0 - 4, -1, -1) if fits(x, y)]
    if spots:
        return min(spots, key=lambda s: (c0 - 4 - s[0]) + 2 * abs(s[1] - top))
    for y in range(0, 5):   # otherwise anywhere in the air above the cat
        for x in range(W - 3, -1, -1):
            if fits(x, y):
                return x, y
    return None

def nose_spot(g, front):
    spots = [(c, r) for r in range(H) for c in range(W) if g[r][c] == 'n']
    if not spots: return None
    c, r = spots[0]
    x, y = (c + 1, r + 1) if front else (c + 1, r)
    x, y = min(x, W - 3), max(y, 2)
    return x, y

def main():
    lines = [
        '// Generated by tools/cat-art/export_cs.py from the cat design scripts there. Do not edit by hand.',
        'namespace DesktopBuddy.Core;',
        '',
        'internal static class CatBreedArt',
        '{',
        '    public static readonly Dictionary<CatBreed, BreedFrames> All = new()',
        '    {',
    ]
    for enum, poses, canvas, render in buddies():
        frames, sweat, nose, palette, drawn = {}, {}, {}, {}, {}
        icon = (0, 0)
        for pose in poses:
            cv = canvas(pose)
            spill = {side: n for side, n in posekit.overflow(cv).items() if n}
            if pose not in posekit.AIRBORNE and spill.get('bottom') == 1:
                del spill['bottom']   # paws resting on the taskbar edge
            assert not spill, f'{enum} {pose} is cut off at the frame edge: {spill}'
            img = render(cv)
            rows = []
            for y in range(H):
                row = ''
                for x in range(W):
                    p = img.getpixel((x, y))
                    if p[3] == 0: row += '.'; continue
                    argb = 0xFF000000 | (p[0] << 16) | (p[1] << 8) | p[2]
                    if argb not in palette: palette[argb] = CHARS[len(palette)]
                    row += palette[argb]
                rows.append(row)
            frames[pose] = rows
            if pose in SWEAT_POSES:
                drawn[pose] = (img, cv.headbox)
            if pose in NOSE_POSES:
                n = nose_spot(cv.g, cv.headset in FRONT_HEADS)
                if n: nose[pose] = n
            if pose == 'Sit':
                r0, c0, h, w = cv.headbox
                icon = (max(0, min(W - 16, c0 + w // 2 - 8)), max(0, min(H - 12, r0 - 1)))
        for group in SWEAT_GROUPS:
            s = sweat_spot([drawn[p] for p in group])
            if s: sweat.update((p, s) for p in group)
        lines.append(f'        [CatBreed.{enum}] = new(')
        lines.append('            new Dictionary<char, uint>')
        lines.append('            {')
        for argb, ch in palette.items():
            lines.append(f"                ['{ch}'] = 0x{argb:08X},")
        lines.append('            },')
        lines.append('            new Dictionary<CatPose, string[]>')
        lines.append('            {')
        for pose, rows in frames.items():
            lines.append(f'                [CatPose.{pose}] = new[]')
            lines.append('                {')
            lines += [f'                    "{row}",' for row in rows]
            lines.append('                },')
        lines.append('            },')
        lines.append('            new Dictionary<CatPose, (int X, int Y)>')
        lines.append('            {')
        lines += [f'                [CatPose.{p}] = ({x}, {y}),' for p, (x, y) in sweat.items()]
        lines.append('            },')
        lines.append('            new Dictionary<CatPose, (int X, int Y)>')
        lines.append('            {')
        lines += [f'                [CatPose.{p}] = ({x}, {y}),' for p, (x, y) in nose.items()]
        lines.append('            },')
        lines.append(f'            IconLeft: {icon[0]}, IconTop: {icon[1]}),')
        print(f'{enum}: {len(palette)} colours, sweat {len(sweat)}/{len(SWEAT_POSES)}, nose {len(nose)}/{len(NOSE_POSES)}, icon {icon}')
        assert len(palette) <= len(CHARS)
    lines += ['    };', '}', '']
    with open(OUT, 'w', newline='\n', encoding='utf-8') as f:
        f.write('\n'.join(lines))

if __name__ == '__main__':
    main()
