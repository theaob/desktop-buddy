"""Writes src/DesktopBuddy.Core/CatBreedArt.cs: every pose of the ten designed cats as pixel grids.
Run from this folder: python3 export_cs.py"""
import os
import posekit, final, drafts

W, H = posekit.W, posekit.H
OUT = os.path.join(os.path.dirname(__file__), '..', '..', 'src', 'DesktopBuddy.Core', 'CatBreedArt.cs')
CHARS = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789!#$%&()*+,-/:;<=>?@[]^_`{|}~"
SWEAT = [(1, 0), (0, 1), (1, 1), (2, 1), (0, 2), (1, 2), (2, 2), (1, 3)]   # drop shape, as in CatPixels
SWEAT_POSES = ['WalkA', 'WalkB', 'Sit', 'SitBlink', 'LookUp', 'SitTail', 'RunA', 'RunB', 'RunC', 'RunD']
NOSE_POSES = ['SitBlink', 'NapA', 'NapB', 'Drowsy', 'Curl']
BUBBLE = [(dx, dy) for dx in range(3) for dy in range(3)]
FRONT_HEADS = {'bean', 'puff', 'pebble', 'sprout'}

def cats():
    """(enum name, settings label, kw for posekit, renderer) for each designed cat."""
    for name, _, kw, coat in drafts.DRAFTS:
        yield (f'{name}Cartoon', f'{name} (cartoon)', kw,
               lambda g, name=name, coat=coat: drafts.render(name, drafts.fluffy(g) if name == 'Puff' else g, coat))
    for name, _, kind, fluff, coat in final.CATS:
        yield (f'{name}Realistic', f'{name} (realistic)', dict(kind=kind),
               lambda g, fluff=fluff, coat=coat: final.render(final.fluffy(g) if fluff else g, coat))

def clear(img, x, y, shape, margin=1):
    for dx, dy in shape:
        for mx in range(-margin, margin + 1):
            for my in range(-margin, margin + 1):
                px, py = x + dx + mx, y + dy + my
                if not (0 <= px < W and 0 <= py < H):
                    if mx == 0 and my == 0: return False
                    continue
                if img.getpixel((px, py))[3]: return False
    return True

def sweat_spot(img, head):
    r0, c0, h, w = head
    for y in range(max(0, r0 - 1), r0 + 5):
        for x in range(c0 - 4, -1, -1):
            if clear(img, x, y, SWEAT):
                return x, y
    for y in range(0, 5):   # otherwise anywhere in the air above the cat
        for x in range(W - 3, -1, -1):
            if clear(img, x, y, SWEAT):
                return x, y
    return None

def nose_spot(g, front):
    spots = [(c, r) for r in range(H) for c in range(W) if g[r][c] == 'n']
    if not spots: return None
    c, r = spots[0]
    x, y = (c + 1, r + 1) if front else (c + 1, r)
    x, y = min(x, W - 3), max(y, 2)
    return x, y

def main():
    lines = [
        '// Generated by tools/cat-art/export_cs.py from the cat design scripts there. Do not edit by hand.',
        'namespace DesktopBuddy.Core;',
        '',
        'internal static class CatBreedArt',
        '{',
        '    public static readonly Dictionary<CatBreed, BreedFrames> All = new()',
        '    {',
    ]
    labels = []
    for enum, label, kw, render in cats():
        labels.append((enum, label))
        frames, sweat, nose, palette = {}, {}, {}, {}
        icon = (0, 0)
        for pose in posekit.POSES:
            cv = posekit.pose_canvas(pose, **kw)
            spill = {side: n for side, n in posekit.overflow(cv).items() if n}
            if pose not in posekit.AIRBORNE and spill.get('bottom') == 1:
                del spill['bottom']   # paws resting on the taskbar edge
            assert not spill, f'{enum} {pose} is cut off at the frame edge: {spill}'
            img = render(cv.g)
            rows = []
            for y in range(H):
                row = ''
                for x in range(W):
                    p = img.getpixel((x, y))
                    if p[3] == 0: row += '.'; continue
                    argb = 0xFF000000 | (p[0] << 16) | (p[1] << 8) | p[2]
                    if argb not in palette: palette[argb] = CHARS[len(palette)]
                    row += palette[argb]
                rows.append(row)
            frames[pose] = rows
            if pose in SWEAT_POSES:
                s = sweat_spot(img, cv.headbox)
                if s: sweat[pose] = s
            if pose in NOSE_POSES:
                n = nose_spot(cv.g, cv.headset in FRONT_HEADS)
                if n: nose[pose] = n
            if pose == 'Sit':
                r0, c0, h, w = cv.headbox
                icon = (max(0, min(W - 16, c0 + w // 2 - 8)), max(0, min(H - 12, r0 - 1)))
        lines.append(f'        [CatBreed.{enum}] = new(')
        lines.append('            new Dictionary<char, uint>')
        lines.append('            {')
        for argb, ch in palette.items():
            lines.append(f"                ['{ch}'] = 0x{argb:08X},")
        lines.append('            },')
        lines.append('            new Dictionary<CatPose, string[]>')
        lines.append('            {')
        for pose, rows in frames.items():
            lines.append(f'                [CatPose.{pose}] = new[]')
            lines.append('                {')
            lines += [f'                    "{row}",' for row in rows]
            lines.append('                },')
        lines.append('            },')
        lines.append('            new Dictionary<CatPose, (int X, int Y)>')
        lines.append('            {')
        lines += [f'                [CatPose.{p}] = ({x}, {y}),' for p, (x, y) in sweat.items()]
        lines.append('            },')
        lines.append('            new Dictionary<CatPose, (int X, int Y)>')
        lines.append('            {')
        lines += [f'                [CatPose.{p}] = ({x}, {y}),' for p, (x, y) in nose.items()]
        lines.append('            },')
        lines.append(f'            IconLeft: {icon[0]}, IconTop: {icon[1]}),')
        print(f'{enum}: {len(palette)} colours, sweat {len(sweat)}/{len(SWEAT_POSES)}, nose {len(nose)}/{len(NOSE_POSES)}, icon {icon}')
        assert len(palette) <= len(CHARS)
    lines += ['    };', '}', '']
    with open(OUT, 'w', newline='\n') as f:
        f.write('\n'.join(lines))

if __name__ == '__main__':
    main()
